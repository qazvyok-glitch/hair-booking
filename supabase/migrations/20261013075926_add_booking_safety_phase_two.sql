create table if not exists public.booking_system_config (
  singleton boolean primary key default true check (singleton),
  data_mode text not null default 'test' check (data_mode in ('test', 'live')),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

insert into public.booking_system_config (singleton, data_mode)
values (true, 'test')
on conflict (singleton) do nothing;

alter table public.booking_system_config enable row level security;

create policy "booking mode is readable"
on public.booking_system_config for select
to anon, authenticated
using (true);

alter table public.bookings
  add column if not exists is_test_data boolean not null default true,
  add column if not exists completed_at timestamptz,
  add column if not exists locked_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

comment on column public.bookings.is_test_data is
  'True while the shop is in test mode. Test bookings remain editable and purgeable.';

create table if not exists public.booking_audit_logs (
  id bigint generated by default as identity primary key,
  booking_id integer,
  action text not null check (action in ('created', 'updated', 'status_changed', 'deleted')),
  before_data jsonb,
  after_data jsonb,
  actor_user_id uuid,
  actor_username text not null default 'anonymous',
  actor_role text not null default 'customer',
  is_test_data boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists booking_audit_logs_booking_id_created_at_idx
  on public.booking_audit_logs (booking_id, created_at desc);

alter table public.booking_audit_logs enable row level security;

create policy "active admins read booking audit logs"
on public.booking_audit_logs for select
to authenticated
using (
  exists (
    select 1
    from public.admin_profiles p
    where p.user_id = (select auth.uid())
      and p.is_active
  )
);

revoke insert, update, delete on public.booking_audit_logs from anon, authenticated;
grant select on public.booking_audit_logs to authenticated;

create or replace function public.set_booking_runtime_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_mode text;
begin
  if tg_op = 'INSERT' then
    select c.data_mode into current_mode
    from public.booking_system_config c
    where c.singleton = true;

    new.is_test_data := coalesce(current_mode, 'test') = 'test';
  else
    new.is_test_data := old.is_test_data;
  end if;

  new.updated_at := now();

  if tg_op = 'INSERT' then
    if new.status = 'completed' then
      new.completed_at := now();
      if not new.is_test_data then
        new.locked_at := now();
      end if;
    end if;
  else
    if new.status = 'completed' and old.status is distinct from 'completed' then
      new.completed_at := now();
      if not new.is_test_data then
        new.locked_at := now();
      end if;
    elsif new.status is distinct from 'completed' then
      new.completed_at := null;
      if new.is_test_data then
        new.locked_at := null;
      end if;
    end if;
  end if;

  return new;
end;
$$;

create or replace function public.is_current_admin_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_profiles p
    where p.user_id = auth.uid()
      and p.is_active
      and p.role = 'owner'
  )
$$;

revoke all on function public.is_current_admin_owner() from public;
grant execute on function public.is_current_admin_owner() to authenticated;

create or replace function public.enforce_booking_safety()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  is_owner boolean := public.is_current_admin_owner();
  start_at timestamp;
  end_at timestamp;
begin
  if tg_op = 'DELETE' then
    if old.is_test_data or is_owner then
      return old;
    end if;
    raise exception 'BOOKING_LOCKED: 正式預約不可刪除，請由最高管理員執行更正';
  end if;

  if tg_op = 'UPDATE' and not old.is_test_data then
    if old.locked_at is not null and not is_owner then
      raise exception 'BOOKING_LOCKED: 此預約已完成並鎖定';
    end if;

    if new.status is distinct from old.status and not is_owner then
      if not (
        (old.status = 'pending' and new.status in ('confirmed', 'cancelled'))
        or (old.status = 'confirmed' and new.status in ('completed', 'cancelled'))
      ) then
        raise exception 'INVALID_BOOKING_STATUS_TRANSITION: 不允許的預約狀態變更';
      end if;
    end if;
  end if;

  if new.designer_id is not null
     and new.status in ('pending', 'confirmed', 'completed')
     and new.booking_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
     and (
       tg_op = 'INSERT'
       or new.designer_id is distinct from old.designer_id
       or new.booking_date is distinct from old.booking_date
       or new.booking_time is distinct from old.booking_time
       or new.duration_minutes is distinct from old.duration_minutes
       or new.status is distinct from old.status
     ) then
    perform pg_advisory_xact_lock(
      hashtextextended(new.designer_id::text || ':' || new.booking_date::text, 0)
    );

    start_at := new.booking_date + new.booking_time::time;
    end_at := start_at + make_interval(mins => greatest(coalesce(new.duration_minutes, 60), 15));

    if exists (
      select 1
      from public.bookings b
      where b.designer_id = new.designer_id
        and b.id <> coalesce(new.id, -1)
        and b.status in ('pending', 'confirmed', 'completed')
        and b.booking_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
        and (b.booking_date + b.booking_time::time) < end_at
        and (
          b.booking_date + b.booking_time::time
          + make_interval(mins => greatest(coalesce(b.duration_minutes, 60), 15))
        ) > start_at
    ) then
      raise exception 'BOOKING_TIME_CONFLICT: 此設計師在該時段已有預約';
    end if;
  end if;

  return new;
end;
$$;

create or replace function public.audit_booking_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile public.admin_profiles;
  action_name text;
  row_id integer;
  test_flag boolean;
begin
  select p into profile
  from public.admin_profiles p
  where p.user_id = auth.uid() and p.is_active
  limit 1;

  if tg_op = 'INSERT' then
    action_name := 'created';
    row_id := new.id;
    test_flag := new.is_test_data;
  elsif tg_op = 'DELETE' then
    action_name := 'deleted';
    row_id := old.id;
    test_flag := old.is_test_data;
  else
    action_name := case when new.status is distinct from old.status then 'status_changed' else 'updated' end;
    row_id := new.id;
    test_flag := new.is_test_data;
  end if;

  insert into public.booking_audit_logs (
    booking_id, action, before_data, after_data, actor_user_id,
    actor_username, actor_role, is_test_data
  ) values (
    row_id,
    action_name,
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end,
    auth.uid(),
    coalesce(profile.username, case when auth.uid() is null then 'anonymous' else auth.uid()::text end),
    coalesce(profile.role_name, case when auth.uid() is null then 'customer' else 'member' end),
    test_flag
  );

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

