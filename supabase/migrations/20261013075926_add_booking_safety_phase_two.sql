for each row execute function public.audit_booking_change();

create or replace function public.set_booking_data_mode(
  target_mode text,
  confirmation text
)
returns public.booking_system_config
language plpgsql
security definer
set search_path = ''
as $$
declare
  result public.booking_system_config;
begin
  if not public.is_current_admin_owner() then
    raise exception 'permission denied';
  end if;

  if target_mode not in ('test', 'live') then
    raise exception 'invalid data mode';
  end if;

  if confirmation <> (case when target_mode = 'live' then '切換正式模式' else '切換測試模式' end) then
    raise exception 'confirmation text does not match';
  end if;

  update public.booking_system_config
  set data_mode = target_mode, updated_at = now(), updated_by = auth.uid()
  where singleton = true
  returning * into result;

  return result;
end;
$$;

revoke all on function public.set_booking_data_mode(text, text) from public;
grant execute on function public.set_booking_data_mode(text, text) to authenticated;

create or replace function public.clear_test_booking_data(confirmation text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  booking_count integer;
  transaction_count integer;
  material_count integer;
  audit_count integer;
begin
  if not public.is_current_admin_owner() then
    raise exception 'permission denied';
  end if;

  if confirmation <> '清除全部測試預約' then
    raise exception 'confirmation text does not match';
  end if;

  select count(*) into booking_count from public.bookings where is_test_data;
  select count(*) into transaction_count
  from public.transactions t
  where exists (select 1 from public.bookings b where b.id = t.booking_id and b.is_test_data);
  select count(*) into material_count
  from public.material_usage m
  where exists (select 1 from public.bookings b where b.id = m.booking_id and b.is_test_data);
  select count(*) into audit_count from public.booking_audit_logs where is_test_data;

  delete from public.material_usage m
  where exists (select 1 from public.bookings b where b.id = m.booking_id and b.is_test_data);

  delete from public.transactions t
  where exists (select 1 from public.bookings b where b.id = t.booking_id and b.is_test_data);

  delete from public.booking_audit_logs where is_test_data;
  delete from public.bookings where is_test_data;

  return jsonb_build_object(
    'bookings', booking_count,
    'transactions', transaction_count,
    'material_usage', material_count,
    'audit_logs', audit_count
  );
end;
$$;

revoke all on function public.clear_test_booking_data(text) from public;
grant execute on function public.clear_test_booking_data(text) to authenticated;

grant select on public.booking_system_config to anon, authenticated;
