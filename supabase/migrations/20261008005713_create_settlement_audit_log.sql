create table if not exists public.settlement_audit_logs (
  id bigint generated by default as identity primary key,
  settlement_month text not null check (settlement_month ~ '^\\d{4}-\\d{2}$'),
  designer_id bigint,
  designer_name text not null default '',
  event_type text not null check (event_type in ('detail_update', 'historical_correction', 'settlement_confirmed', 'settlement_unlocked')),
  category text not null default '',
  item_name text not null default '',
  before_name text,
  after_name text,
  before_amount numeric not null default 0,
  after_amount numeric not null default 0,
  reason text not null,
  admin_username text not null,
  admin_role_name text not null,
  created_at timestamptz not null default now()
);

create index if not exists settlement_audit_logs_month_created_idx
  on public.settlement_audit_logs (settlement_month, created_at desc);

alter table public.settlement_audit_logs enable row level security;

revoke all on table public.settlement_audit_logs from anon, authenticated;
grant select, insert on table public.settlement_audit_logs to anon, authenticated;
grant usage, select on sequence public.settlement_audit_logs_id_seq to anon, authenticated;

drop policy if exists "settlement audit read" on public.settlement_audit_logs;
create policy "settlement audit read"
  on public.settlement_audit_logs for select
  to anon, authenticated
  using (true);

drop policy if exists "settlement audit append" on public.settlement_audit_logs;
create policy "settlement audit append"
  on public.settlement_audit_logs for insert
  to anon, authenticated
  with check (length(trim(admin_username)) > 0 and length(trim(reason)) > 0);

create or replace function public.prevent_settlement_audit_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'settlement audit logs are append-only';
end;
$$;

revoke all on function public.prevent_settlement_audit_mutation() from public;

drop trigger if exists settlement_audit_logs_immutable on public.settlement_audit_logs;
create trigger settlement_audit_logs_immutable
before update or delete on public.settlement_audit_logs
for each row execute function public.prevent_settlement_audit_mutation();
